const MONTHS_PREPOSITIONAL = [
  'январе',
  'феврале',
  'марте',
  'апреле',
  'мае',
  'июне',
  'июле',
  'августе',
  'сентябре',
  'октябре',
  'ноябре',
  'декабре'
]

export function getBlogMonthLabel(isoDate, now = new Date()) {
  const date = new Date(`${isoDate}T00:00:00`)
  const year = date.getFullYear()
  const sameMonth = year === now.getFullYear() && date.getMonth() === now.getMonth()

  if (sameMonth) {
    return 'В этом месяце'
  }

  const monthLabel = `В ${MONTHS_PREPOSITIONAL[date.getMonth()]}`
  if (year === now.getFullYear()) {
    return monthLabel
  }

  return `${monthLabel} ${year}`
}

export function getBlogMonthKey(isoDate) {
  return isoDate.slice(0, 7)
}

export function getBlogArticleById(id) {
  const articleId = Number(id)
  if (!Number.isFinite(articleId)) return null
  return blogArticles.find(article => article.id === articleId) ?? null
}
